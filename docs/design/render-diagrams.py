ROOT.mkdir(parents=True, exist_ok=True)
for slug, title, direction, nodes, edges in SPECS:
    mermaid = [f"flowchart {direction}"]
    decisions = {key for key, label in nodes.items() if label.endswith("?")}
    if slug == "01-network-loss": decisions.add("G")
    mermaid += [f"    {key}" + ("{" if key in decisions else "[") + json.dumps(label, ensure_ascii=False) + ("}" if key in decisions else "]") for key, label in nodes.items()]
    mermaid += [f"    {a} -->|{label}| {b}" if label else f"    {a} --> {b}" for a, b, label in edges]
    (ROOT / f"{slug}.mmd").write_text("\n".join(mermaid) + "\n")
    dot = ["digraph G {", f'rankdir={"TB" if direction == "TD" else "LR"};',
           'graph [bgcolor="#F5F7FC", pad="0.35", nodesep="0.35", ranksep="0.5", fontname="DejaVu Sans", fontsize=20, labelloc="t", label=' + json.dumps(title, ensure_ascii=False) + '];',
           'node [shape=box, style="rounded,filled", fillcolor="#FFFFFF", color="#779AD0", fontcolor="#172B45", fontname="DejaVu Sans", fontsize=12, margin="0.18,0.15"];',
           'edge [color="#315D9A", fontcolor="#254A7B", fontname="DejaVu Sans", fontsize=10];']
    dot += [f"{key} [shape={'diamond' if key in decisions else 'box'}, label={json.dumps(label, ensure_ascii=False)}];" for key, label in nodes.items()]
    dot += [f"{a} -> {b} [label={json.dumps(label, ensure_ascii=False)}];" for a, b, label in edges]
    dot.append("}")
    path = ROOT / f"{slug}.dot"
    path.write_text("\n".join(dot) + "\n")
    for fmt in ("svg", "png"):
        subprocess.run(["dot", f"-T{fmt}", str(path), "-o", str(ROOT / f"{slug}.{fmt}")], check=True)
print(f"Generated {len(SPECS)} diagrams: Mermaid, DOT, SVG, PNG.")

# Keep the Mermaid blocks in the design document aligned with the editable sources.
import re
md = ROOT.parent / "system-v2.md"
if md.exists():
    content = md.read_text()
    for slug, title, *_ in SPECS:
        pattern = r"(?s)(### " + re.escape(title) + r"\n.*?```mermaid\n).*?(```)"
        source = (ROOT / f"{slug}.mmd").read_text()
        content = re.sub(pattern, lambda match: match[1] + source + match[2], content, count=1)
    md.write_text(content)
